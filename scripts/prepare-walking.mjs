// Data preparation only: walking distances between sights along OpenStreetMap
// streets, from the committed snapshot artifacts/atlas-osm-20260920.xml.
// Same edge rules as the atlas itineraries: highway ways only, excluding
// access=private/no, foot=no and area=yes. Writes src/data/placeWalking.js.
import fs from 'node:fs'
import { PLACES } from '../src/data/pages.js'

const xml = fs.readFileSync(new URL('../artifacts/atlas-osm-20260920.xml', import.meta.url), 'utf8')
const nodes = new Map([...xml.matchAll(/<node\b([^>]+)/g)].map((m) => {
  const a = Object.fromEntries([...m[1].matchAll(/(\w+)="([^"]*)"/g)].map((v) => [v[1], v[2]]))
  return [a.id, [+a.lon, +a.lat]]
}))
const distance = (a, b) =>
  Math.hypot((a[0] - b[0]) * Math.cos((24.055 * Math.PI) / 180), a[1] - b[1]) * 111195
const graph = new Map()
const link = (a, b, d) => {
  if (!graph.has(a)) graph.set(a, [])
  graph.get(a).push([b, d])
}
for (const m of xml.matchAll(/<way\b[^>]+>([\s\S]*?)<\/way>/g)) {
  const tags = Object.fromEntries([...m[1].matchAll(/<tag k="([^"]+)" v="([^"]+)"\/>/g)].map((t) => [t[1], t[2]]))
  if (!tags.highway || ['no', 'private'].includes(tags.access) || tags.foot === 'no' || tags.area === 'yes') continue
  if (['motorway', 'motorway_link', 'trunk', 'trunk_link'].includes(tags.highway)) continue
  const ids = [...m[1].matchAll(/<nd ref="(\d+)"\/>/g)].map((n) => n[1]).filter((id) => nodes.has(id))
  ids.slice(1).forEach((id, i) => {
    const d = distance(nodes.get(ids[i]), nodes.get(id))
    link(ids[i], id, d)
    link(id, ids[i], d)
  })
}
// Largest connected component, so no sight snaps onto an isolated fragment.
const seen = new Set()
let main = []
for (const start of graph.keys()) {
  if (seen.has(start)) continue
  const part = [start]
  seen.add(start)
  for (let i = 0; i < part.length; i++)
    for (const [next] of graph.get(part[i])) if (!seen.has(next)) seen.add(next) && part.push(next)
  if (part.length > main.length) main = part
}
const snap = (point) =>
  main.reduce((best, id) => {
    const d = distance(point, nodes.get(id))
    return d < best.d ? { id, d } : best
  }, { id: null, d: Infinity })
function shortest(from) {
  const dist = new Map([[from, 0]])
  const done = new Set()
  const queue = [[0, from]]
  while (queue.length) {
    queue.sort((a, b) => a[0] - b[0])
    const [d, id] = queue.shift()
    if (done.has(id)) continue
    done.add(id)
    for (const [next, w] of graph.get(id)) {
      const nd = d + w
      if (nd < (dist.get(next) ?? Infinity)) {
        dist.set(next, nd)
        queue.push([nd, next])
      }
    }
  }
  return dist
}
const snapped = Object.fromEntries(PLACES.map((p) => [p.id, snap(p.coordinates)]))
const walking = {}
for (const place of PLACES) {
  const dist = shortest(snapped[place.id].id)
  walking[place.id] = Object.fromEntries(
    PLACES.filter((p) => p.id !== place.id).map((p) => [
      p.id,
      Math.round(dist.get(snapped[p.id].id) + snapped[place.id].d + snapped[p.id].d),
    ]),
  )
}
for (const [id, s] of Object.entries(snapped)) if (s.d > 40) console.warn(`${id} snaps ${Math.round(s.d)} m from the street network`)
fs.writeFileSync(
  new URL('../src/data/placeWalking.js', import.meta.url),
  `// Generated by scripts/prepare-walking.mjs from © OpenStreetMap contributors (ODbL),\n// snapshot 2026-09-20. Metres along streets between sight representative points.\nexport const PLACE_WALKING = ${JSON.stringify(walking, null, 2)}\n`,
)
